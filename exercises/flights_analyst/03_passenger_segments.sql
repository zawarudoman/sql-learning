/* =====================================================================
   ANALYST 3. Сегментация пассажиров по числу перелётов
   ---------------------------------------------------------------------
   БИЗНЕС-ВОПРОС:
   Как распределены пассажиры по «летучести»? Сколько разовых,
   сколько регулярных, сколько частолетающих?

   ЧТО ВЫВЕСТИ:
   • сегмент: '1 перелёт', '2-5 перелётов', '6+ перелётов',
   • сколько пассажиров в каждом сегменте,
   • их доля от всех пассажиров в % (round, 1).
   Отсортируй по числу пассажиров (или логично по сегменту).

   ГДЕ ДАННЫЕ:
   • пассажир = tickets.passenger_id (у одного человека может быть много билетов),
   • перелёт = строка в segments (ticket_no → сегменты по билетам пассажира).

   ТЕХНИКА (двухуровневая агрегация — классика аналитики):
   1) CTE: для каждого passenger_id посчитай число перелётов
      (segments по его билетам). Понадобится JOIN tickets + segments.
   2) снаружи: разложи это число по сегментам через CASE, и сгруппируй.
      Долю от общего дай через SUM(...) OVER () или подзапросом с общим числом.

   Подумай про CASE-бакеты:
     CASE WHEN cnt = 1 THEN '1 перелёт'
          WHEN cnt BETWEEN 2 AND 5 THEN '2-5 перелётов'
          ELSE '6+ перелётов' END
   ===================================================================== */

SELECT COUNT(*), passenger_id
FROM tickets t
JOIN segments s ON t.ticket_no = s.ticket_no
group by t.passenger_id



