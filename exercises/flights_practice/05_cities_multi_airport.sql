/* =====================================================================
   PRACTICE 5. Города с несколькими аэропортами
   Навык: GROUP BY + HAVING
   ---------------------------------------------------------------------
   Найди города, в которых БОЛЬШЕ ОДНОГО аэропорта.
   Выведи: город, число аэропортов. Больше аэропортов — выше.

   Вспомни: условие на количество в группе → HAVING (не WHERE).

   Схема: airports (airport_code, city).
   ===================================================================== */

SELECT a.city as city, COUNT(a.airport_name) as count_airport
FROM airports a
GROUP BY a.city
HAVING COUNT(a.airport_name) > 1
ORDER BY count_airport DESC

