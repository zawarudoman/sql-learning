/* =====================================================================
   PRACTICE 6. Дальнобойные самолёты
   Навык: скалярный подзапрос + сравнение
   ---------------------------------------------------------------------
   Выведи модели самолётов, у которых дальность полёта (range) БОЛЬШЕ
   средней дальности по всему парку.
   Столбцы: модель, дальность. Дальние — сверху.

   Схема: airplanes (airplane_code, model, range, speed).
   Подсказка: среднее — подзапрос (SELECT AVG(range) FROM airplanes).
   ===================================================================== */

SELECT a.model, a.range
FROM airplanes a
WHERE a.range > (SELECT AVG(range) FROM airplanes)
ORDER BY a.range DESC