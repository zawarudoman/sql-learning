/* =====================================================================
   HARD 1. Пунктуальность маршрутов — с двумя ловушками
   Темы: агрегаты + NULL + деление + именование
   ---------------------------------------------------------------------
   ЗАДАЧА:
   Для каждого маршрута (route_no) посчитай:
     • всего рейсов по расписанию,
     • сколько реально вылетело,
     • процент вылетевших (доля выполненных рейсов, 0–100),
     • среднюю задержку вылета в минутах (только по вылетевшим).
   Оставь только маршруты, где по расписанию было >= 50 рейсов.
   Сортировка: по средней задержке, худшие сверху.

   ⚠️ Здесь зарыты грабли — подумай ДО того, как писать:
   1. "всего рейсов" и "средняя задержка" считаются по РАЗНЫМ множествам
      (все vs только вылетевшие). Как не смешать их в одной строке?
   2. процент = вылетевшие / всего. Если оба integer — получишь целочисленное
      деление (0 или 1). Как заставить считать дробь?
   3. дай всем столбцам осмысленные имена.

   Схема: flights (route_no, scheduled_departure, actual_departure).
   Задержка в минутах: EXTRACT(EPOCH FROM (actual_departure - scheduled_departure))/60
   ===================================================================== */


SELECT t.route_no,
       COUNT(*)                    AS total_flights,
       COUNT(t.actual_departure)   AS departed_flights,
       round(COUNT(t.actual_departure)* 100.0 / COUNT(*), 2) AS pct_departed,
       round(AVG(EXTRACT(EPOCH FROM (t.actual_departure - t.scheduled_departure))/60),2) AS avg_delay_min
FROM timetable t
GROUP BY t.route_no
HAVING COUNT(*) >=50
ORDER BY avg_delay_min DESC;

