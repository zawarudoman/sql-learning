SELECT a.model, SUM(s.price) as summ, COUNT(DISTINCT(s.fare_conditions)) AS cnt_fare
FROM segments s JOIN timetable t ON t.flight_id=s.flight_id
join airplanes a on a.airplane_code = t.airplane_code
GROUP BY a.model;

SELECT SUM(price) FROM segments;






