   число сегментов. Прибыльные — сверху.

   ⚠️ ОБЯЗАТЕЛЬНАЯ САМОПРОВЕРКА (часть оценки):
   отдельным запросом посчитай общую SUM(price) по всей таблице segments
   и сравни с суммой всех строк своего отчёта.
   Не совпало — значит какой-то JOIN размножил строки, ищи его.

   Запиши в комментарии обе цифры и вывод: совпало / не совпало.
