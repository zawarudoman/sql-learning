/* =====================================================================
   ЭКЗАМЕН 1 · Задача 1 (5 баллов)
   ---------------------------------------------------------------------
   Прежде чем что-то считать — надо знать, какие данные вообще есть.

   Одним запросом выведи по таблице bookings:
     • самую раннюю дату бронирования,
     • самую позднюю дату бронирования,
     • общее число бронирований,
     • общую сумму,
     • средний чек (округли до 2 знаков).

   Одна строка на выходе. Столбцам дай осмысленные имена.
   ===================================================================== */

SELECT MIN(b.book_date)    as early_date,
       MAX(b.book_date)    as late_date,
       COUNT(*)            as cnt_booking,
       SUM(b.total_amount) as sum_amount,
       ROUND(AVG(b.total_amount), 2) as avg_total
FROM bookings b