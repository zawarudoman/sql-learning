/* =====================================================================
   Задание 5. Топ-10 самых задержанных рейсов        ⭐ НОВАЯ ТЕМА: CTE
   Тема: CTE (WITH ...) — раскладываем запрос на читаемые шаги
   ---------------------------------------------------------------------
   ЧТО ТАКОЕ CTE:
   WITH имя AS ( ... запрос ... )
   SELECT ... FROM имя ...

   Это "временная именованная таблица" на время запроса. Позволяет
   разложить сложную логику на шаги вместо матрёшки из подзапросов.
   Читается сверху вниз, как рецепт.

   ---------------------------------------------------------------------
   ЗАДАЧА:
   Найди 10 рейсов с самой большой задержкой вылета.
   Столбцы: flight_id, route_no, плановый вылет, фактический вылет, задержка.

   Задержка = actual_departure - scheduled_departure (получится interval).
   Учти: у не улетевших рейсов actual_departure пустой (NULL) — их не берём.

   Сделай через CTE: сначала в WITH посчитай задержку, потом снаружи
   отбери топ-10. Так будет читаемо.
   ===================================================================== */

WITH delays AS (SELECT (t.actual_departure - t.scheduled_departure) AS delay,
                       t.flight_id                                  as flight_id,
                       t.route_no,
                       t.actual_departure,
                       t.scheduled_departure
                FROM timetable t
                where t.actual_departure IS NOT NULL)
SELECT *
FROM delays
ORDER BY delay DESC
LIMIT 10

