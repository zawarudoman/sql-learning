/* =====================================================================
   Задание 1. Рейсы с городами вылета и прилёта
   Навык: JOIN одной и той же таблицы ДВАЖДЫ с разными алиасами
   ---------------------------------------------------------------------
   Суть: в flights нет аэропортов — они лежат в routes.
   А города лежат в airports, поэтому к airports джойнимся два раза:
   один раз ради города вылета, второй — ради города прилёта.
   ===================================================================== */

SELECT f.flight_id,
       a.city  AS откуда,
       aa.city AS куда,
       f.scheduled_departure
FROM bookings.routes   r
JOIN bookings.airports a  ON r.departure_airport = a.airport_code   -- город вылета
JOIN bookings.airports aa ON r.arrival_airport   = aa.airport_code  -- город прилёта
JOIN bookings.flights  f  ON f.route_no          = r.route_no
FETCH FIRST 10 ROWS ONLY;

/* Что усвоено:
   • одну таблицу можно джойнить несколько раз — разными алиасами (a / aa);
   • GROUP BY без агрегатов не нужен (он лишь схлопывает дубли — для этого есть DISTINCT);
   • одинаковым именам столбцов давать алиасы (иначе в выводе два раза "city").
