/* =====================================================================
   Задание 3. Вместительные самолёты
   Тема: GROUP BY + HAVING (фильтр по агрегату)
   ---------------------------------------------------------------------
   ЗАДАЧА:
   Выведи модели самолётов, в которых БОЛЬШЕ 100 мест.
   Столбцы: модель, количество мест. Больше мест — выше.

   Схема: места — в seats (по одной строке на место, связь airplane_code),
          название модели — в airplanes.model.

   Вспомни правило: WHERE фильтрует строки ДО группировки,
                    HAVING — уже посчитанные группы ПОСЛЕ.
   ===================================================================== */

-- твоё решение:

SELECT COUNT(s.seat_no) as seat_count, ap.model
FROM airplanes ap
         JOIN seats s ON s.airplane_code = ap.airplane_code
GROUP BY ap.model
HAVING COUNT(s.seat_no) > 100
ORDER BY seat_count DESC;
