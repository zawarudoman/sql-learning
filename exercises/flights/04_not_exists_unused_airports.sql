/* =====================================================================
   Задание 4. Аэропорты без вылетов
   Тема: NOT EXISTS (проверка отсутствия связанных записей)
   ---------------------------------------------------------------------
   ЗАДАЧА:
   Найди аэропорты, из которых НЕ вылетает ни один рейс.
   Столбцы: код аэропорта, город, страна.

   Схема: маршруты вылета — routes.departure_airport, рейсы — flights (по route_no).

   Подумай: "нет ни одного связанного" — это свойство ВСЕГО аэропорта,
   его нельзя выразить фильтром одной строки. Нужен NOT EXISTS.
   (Помнишь ловушку с "нет ни одной строки > 100"? Тот же случай.)
   ===================================================================== */


SELECT ap.airport_code, ap.city, ap.country
FROM airports ap
WHERE NOT EXISTS (SELECT 1
                  FROM timetable t
                  WHERE t.departure_airport = ap.airport_code);
