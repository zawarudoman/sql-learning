/* =====================================================================
   Задание 9. Первый рейс каждого маршрута       ⭐ ИДИОМА "одна строка на группу"
   Тема: row_number() → WHERE rn = 1
   ---------------------------------------------------------------------
   ЗАДАЧА:
   Для каждого маршрута выведи ТОЛЬКО его самый первый рейс (по времени
   планового вылета).
   Столбцы: route_no, flight_id, scheduled_departure, status.

   Помни главное про окна:
     оконная функция ПРИПИСЫВАЕТ столбец к каждой строке, но НЕ убирает строки.
   Чтобы СОКРАТИТЬ до одной строки на группу:
     1) пронумеровать row_number() внутри группы в нужном порядке;
     2) обернуть в подзапрос ( ... ) t;
     3) снаружи оставить WHERE t.rn = 1.
   (Оконную функцию нельзя писать прямо в WHERE — потому и подзапрос.)

   Это самый частый оконный приём в реальной работе — освой намертво.
   ===================================================================== */


WITH result_table as (SELECT t.route_no,
                             t.flight_id,
                             t.scheduled_departure,
                             t.status,
                             row_number() OVER (PARTITION BY t.route_no ORDER BY t.scheduled_departure) as rn
                      FROM timetable t)
SELECT rt.route_no, rt.flight_id, rt.scheduled_departure::DATE, rt.status
FROM result_table rt
where rt.rn = 1;

